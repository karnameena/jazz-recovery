import React, { useRef, useState } from "react";
import { LockKeyhole, RefreshCw, ShieldCheck, Sparkles } from "lucide-react";

type Api = (path: string, options?: RequestInit) => Promise<any>;

export function AccountAccess({ api, done }: { api: Api; done: () => void }) {
  const [mode, setMode] = useState<"login" | "register">("login");
  const [error, setError] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [showPassword, setShowPassword] = useState(false);
  const passwordRef = useRef<HTMLInputElement>(null);
  const confirmRef = useRef<HTMLInputElement>(null);

  async function submit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (submitting) return;
    setError("");
    setSubmitting(true);
    const form = event.currentTarget;
    const fields = new FormData(form);
    const username = String(fields.get("username") || "").trim();
    let password = String(fields.get("password") || "");
    const confirmPassword = String(fields.get("confirmPassword") || "");

    if (!username || !password) {
      setError("Enter your username and password.");
      setSubmitting(false);
      return;
    }
    if (mode === "register" && password !== confirmPassword) {
      if (confirmRef.current) confirmRef.current.value = "";
      setError("The passwords do not match.");
      setSubmitting(false);
      return;
    }

    const body: Record<string, string> = { username, password };
    if (mode === "register") {
      body.deviceName = String(fields.get("deviceName") || "").trim();
      body.imei = String(fields.get("imei") || "").replace(/[\\s-]/g, "");
      body.deviceId = String(fields.get("deviceId") || "").trim();
      body.deviceToken = String(fields.get("deviceToken") || "").trim();
    }
    const serialized = JSON.stringify(body);
    password = "";
    if (passwordRef.current) passwordRef.current.value = "";
    if (confirmRef.current) confirmRef.current.value = "";

    try {
      await api(mode === "register" ? "/api/auth/register" : "/api/auth/login", {
        method: "POST",
        body: serialized,
      });
      form.reset();
      done();
    } catch (err) {
      setError(err instanceof Error ? err.message : mode === "register" ? "Registration failed" : "Login failed");
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <main className="auth-shell">
      <div className="ambient ambient-one" />
      <div className="ambient ambient-two" />
      <section className="auth-card glass-panel">
        <div className="brand-mark"><Sparkles size={28} /></div>
        <div className="eyebrow">JAZZ SECURE RECOVERY</div>
        <h1>{mode === "register" ? "Create account" : "Lost Mode"}</h1>
        <p className="auth-subtitle">{mode === "register" ? "Register your account and pair the Android device to start your 7-day trial." : "Secure access to your registered recovery devices."}</p>
        <form onSubmit={submit} className="auth-form" autoComplete="on">
          <label><span>Username</span><input name="username" autoComplete="username" autoCapitalize="none" spellCheck={false} placeholder="Enter username" minLength={3} maxLength={64} required /></label>
          <label><span>Password</span><input ref={passwordRef} name="password" autoComplete={mode === "register" ? "new-password" : "current-password"} type={showPassword ? "text" : "password"} placeholder={mode === "register" ? "Create a strong password" : "Enter password"} required /><button className="text-button" type="button" onClick={() => setShowPassword(value => !value)}>{showPassword ? "Hide password" : "Show password"}</button></label>
          {mode === "register" && <>
            <label><span>Confirm password</span><input ref={confirmRef} name="confirmPassword" autoComplete="new-password" type={showPassword ? "text" : "password"} placeholder="Re-enter password" required /></label>
            <label><span>Device name</span><input name="deviceName" autoComplete="off" maxLength={80} placeholder="e.g. My Android phone" required /></label>
            <label><span>IMEI (14–16 digits)</span><input name="imei" inputMode="numeric" autoComplete="off" minLength={14} maxLength={16} pattern="[0-9]{14,16}" placeholder="Enter device IMEI" required /></label>
            <label><span>Device token ID</span><input name="deviceId" autoComplete="off" minLength={3} maxLength={120} placeholder="Device ID generated by the Jazz app" required /></label>
            <label><span>Device token</span><input name="deviceToken" autoComplete="off" minLength={32} maxLength={512} placeholder="Paste the token generated in the Jazz app" required /></label>
            <p className="auth-hint">Use the device ID and token generated by your installed Jazz Recovery app. The server stores only a token hash, never the plaintext token.</p>
          </>}
          {error && <div className="error-banner" role="alert">{error}</div>}
          <button className="primary-button full-width" type="submit" disabled={submitting}>
            {submitting ? <RefreshCw className="spin" size={18} /> : <LockKeyhole size={18} />}
            {submitting ? "Processing securely…" : mode === "register" ? "Create account & start trial" : "Enter Lost Mode"}
          </button>
        </form>
        <button className="secondary-button full-width auth-switch" type="button" onClick={() => { setMode(value => value === "login" ? "register" : "login"); setError(""); setShowPassword(false); }}>
          {mode === "register" ? "Already registered? Sign in" : "New to Jazz Recovery? Create account"}
        </button>
        <div className="secure-note"><ShieldCheck size={16} /> Secure account and device authentication</div>
      </section>
      <footer className="auth-footer">Developed by 😈gunakarna😈</footer>
    </main>
  );
}
